import React from 'react';
import { Alert } from 'react-native';
import { fireEvent, render, screen, waitFor } from '@testing-library/react-native';
import WeeklyVolumeTargets from '@/app/settings/weekly-volume-targets';
import { getUserGoals, saveWeeklyVolumeTargets } from '@/lib/storage';
import { router } from 'expo-router';
import { syncToSupabase } from '@/lib/sync';
const mockDispatch = jest.fn();
const mockGuard = jest.fn();
jest.mock('expo-router', () => ({ router: { back: jest.fn(), push: jest.fn() }, useNavigation: () => ({ dispatch: mockDispatch }) }));
jest.mock('expo-router/react-navigation', () => ({ usePreventRemove: (...args: unknown[]) => mockGuard(...args) }));
jest.mock('@/components/settings/SettingsPage', () => ({ SettingsPage: ({ children }: { children: React.ReactNode }) => <>{children}</> }));
jest.mock('@/hooks/use-theme-color', () => ({ useThemeColor: () => 'gray' }));
jest.mock('@/lib/storage', () => ({ getUserGoals: jest.fn(), saveWeeklyVolumeTargets: jest.fn() }));
jest.mock('@/lib/sync', () => ({ syncToSupabase: jest.fn() }));
const goals = { calorie_goal: 2000, protein_goal: 150, carb_goal: 200, fat_goal: 65, weekly_volume_targets: { Chest: 12 } };
beforeEach(() => { jest.clearAllMocks(); (getUserGoals as jest.Mock).mockResolvedValue(goals); (saveWeeklyVolumeTargets as jest.Mock).mockResolvedValue(undefined); });
test('recommended fills blanks, preserves edits and waits for Save', async () => {
  await render(<WeeklyVolumeTargets />); await screen.findByDisplayValue('12');
  await fireEvent.changeText(screen.getByLabelText('Lats weekly sets'), '8');
  await fireEvent.press(screen.getByText('Use recommended'));
  expect(screen.getByLabelText('Chest weekly sets').props.value).toBe('12');
  expect(screen.getByLabelText('Lats weekly sets').props.value).toBe('8');
  expect(screen.getByLabelText('Quads weekly sets').props.value).toBe('10');
  expect(screen.getByLabelText('Biceps weekly sets').props.value).toBe('');
  expect(saveWeeklyVolumeTargets).not.toHaveBeenCalled();
  await fireEvent.press(screen.getByText('Save'));
  await waitFor(() => expect(saveWeeklyVolumeTargets).toHaveBeenCalledWith({ Chest: 12, Shoulders: 10, Lats: 8, Glutes: 10, Quads: 10, Hamstrings: 10 }));
  expect(syncToSupabase).toHaveBeenCalled(); expect(router.back).toHaveBeenCalled();
});
test('invalid fields prevent saves, zero clears and failures keep draft and guard', async () => {
  (saveWeeklyVolumeTargets as jest.Mock).mockRejectedValueOnce(new Error('disk'));
  await render(<WeeklyVolumeTargets />); await screen.findByDisplayValue('12');
  await fireEvent.changeText(screen.getByLabelText('Chest weekly sets'), '1.2');
  await fireEvent.press(screen.getByText('Save'));
  await screen.findByText('Chest: Enter a whole number from 1 to 40, or leave blank to clear.');
  expect(saveWeeklyVolumeTargets).not.toHaveBeenCalled();
  await fireEvent.changeText(screen.getByLabelText('Chest weekly sets'), '0');
  await fireEvent.press(screen.getByText('Save'));
  await screen.findByText('Couldn’t save targets. Your changes are still here. Try again.');
  expect(saveWeeklyVolumeTargets).toHaveBeenCalledWith({});
  expect(screen.getByLabelText('Chest weekly sets').props.value).toBe('0');
  expect(mockGuard.mock.calls.at(-1)?.[0]).toBe(true);
});
test('load errors support retry and missing goals link to Nutrition without writing', async () => {
  (getUserGoals as jest.Mock).mockRejectedValueOnce(new Error('disk')).mockResolvedValue(null);
  await render(<WeeklyVolumeTargets />);
  await fireEvent.press(await screen.findByText('Retry loading targets'));
  await fireEvent.press(await screen.findByText('Nutrition settings'));
  expect(router.push).toHaveBeenCalledWith('/settings/nutrition');
  expect(saveWeeklyVolumeTargets).not.toHaveBeenCalled();
});
test('back navigation requires discard confirmation while dirty', async () => {
  const alert = jest.spyOn(Alert, 'alert').mockImplementation(() => {});
  await render(<WeeklyVolumeTargets />); await screen.findByDisplayValue('12');
  await fireEvent.changeText(screen.getByLabelText('Chest weekly sets'), '14');
  const [enabled, guard] = mockGuard.mock.calls.at(-1)!;
  expect(enabled).toBe(true); guard({ data: { action: 'back' } });
  expect(alert).toHaveBeenCalledWith('Discard changes?', expect.any(String), expect.any(Array));
  const buttons = alert.mock.calls.at(-1)![2]!;
  buttons.find(button => button.text === 'Discard')!.onPress!();
  expect(mockDispatch).toHaveBeenCalledWith('back'); alert.mockRestore();
});
